//! The read-only task board and the generated `tasks/BOARD.md`.

use serde_json::Value;

use crate::config::settings::lock_settings;
use crate::core::error::Result;
use crate::core::fsio::write_text_atomic;
use crate::core::time::iso;
use crate::core::workspace::Workspace;
use crate::runtime::checkpoints;
use crate::runtime::leases::{
    lock_is_stale, lock_remaining_seconds, recent_refusals, refusal_detail,
};
use crate::tasks::store::{self, Task};

fn cell(value: Option<&str>) -> String {
    let text = value.filter(|value| !value.is_empty()).unwrap_or("-");
    text.replace('|', "\\|").replace(['\r', '\n'], " ")
}

fn text(value: Option<&str>) -> String {
    value
        .filter(|value| !value.is_empty())
        .unwrap_or("-")
        .replace(['\r', '\n'], " ")
}

pub fn render_board(ws: &Workspace, tasks: &[Task], locks: &[Value], mode: &str) -> String {
    let (_, stale_after) = lock_settings(ws);
    let active: Vec<&Task> = tasks.iter().filter(|task| task.is_active()).collect();
    let checkpoints = active
        .iter()
        .filter(|task| checkpoints::read_checkpoint(ws, &task.id()).is_some())
        .count();
    let mut lines = vec![
        "Task board".to_string(),
        format!(
            "mode: {mode} | active: {} | leases: {} | checkpoints: {checkpoints}",
            active.len(),
            locks.len()
        ),
        String::new(),
        "Tasks".to_string(),
    ];
    let rows = store::board_task_rows(tasks);
    if rows.is_empty() {
        lines.push("  (no active tasks)".to_string());
    } else {
        lines.push(format!(
            "  {:<6} {:<12} {:<12} {:<9} {:<12} {:<12} TITLE",
            "ID", "STATUS", "OWNER", "PRIORITY", "CHECKPOINT", "WAITING ON"
        ));
        for (task, waiting) in rows {
            lines.push(format!(
                "  {:<6} {:<12} {:<12} {:<9} {:<12} {:<12} {}",
                task.id(),
                task.status(),
                task.owner().unwrap_or_else(|| "-".into()),
                task.priority().unwrap_or_else(|| "-".into()),
                checkpoints::format_checkpoint_age(ws, &task.id()),
                waiting,
                task.title()
            ));
        }
    }
    lines.push(String::new());
    lines.push("Leases".to_string());
    if locks.is_empty() {
        lines.push("  (no leases)".to_string());
    } else {
        lines.push(format!(
            "  {:<28} {:<14} {:<8} {:>7} {:>10}  STATE",
            "RESOURCE", "AGENT", "TASK", "TTL", "REMAINING"
        ));
        let mut sorted: Vec<&Value> = locks.iter().collect();
        sorted.sort_by(|a, b| {
            a.get("resource")
                .and_then(Value::as_str)
                .unwrap_or("")
                .cmp(b.get("resource").and_then(Value::as_str).unwrap_or(""))
        });
        for lock in sorted {
            let resource = lock.get("resource").and_then(Value::as_str).unwrap_or("");
            let agent = lock.get("agent").and_then(Value::as_str).unwrap_or("");
            let task = lock.get("task").and_then(Value::as_str).unwrap_or("-");
            let ttl = lock
                .get("ttl_seconds")
                .and_then(Value::as_u64)
                .map(|value| format!("{value}s"))
                .unwrap_or_else(|| "?".into());
            let remaining = lock_remaining_seconds(lock)
                .map(|value| format!("{value}s"))
                .unwrap_or_else(|| "?".into());
            let state = if lock_is_stale(Some(lock), stale_after) {
                "stale"
            } else {
                "held"
            };
            lines.push(format!(
                "  {:<28} {:<14} {:<8} {:>7} {:>10}  {state}",
                truncate(resource, 28),
                truncate(agent, 14),
                task,
                ttl,
                remaining
            ));
        }
    }
    lines.push(String::new());
    lines.push("Refusals".to_string());
    let refusals = recent_refusals(ws, 5);
    if refusals.is_empty() {
        lines.push("  (none)".to_string());
    } else {
        for event in refusals {
            lines.push(format!(
                "  {}  {} -> {} ({})",
                event
                    .get("timestamp")
                    .and_then(Value::as_str)
                    .unwrap_or("-"),
                event.get("agent").and_then(Value::as_str).unwrap_or("-"),
                event.get("resource").and_then(Value::as_str).unwrap_or("-"),
                refusal_detail(&event)
            ));
        }
    }
    lines.join("\n")
}

pub fn write_board(ws: &Workspace, tasks: &[Task]) -> Result<()> {
    let mut lines = vec![
        "# Task Board".to_string(),
        String::new(),
        "Generated by `ai task list`. Do not edit by hand.".to_string(),
        String::new(),
    ];
    let active: Vec<&Task> = tasks.iter().filter(|task| task.is_active()).collect();
    let done: Vec<&Task> = tasks.iter().filter(|task| task.folder == "done").collect();
    lines.push(format!(
        "Active: {} | Done: {} | Updated: {}",
        active.len(),
        done.len(),
        iso(None)
    ));
    lines.push(String::new());
    if active.is_empty() {
        lines.push("_No active tasks._".to_string());
        lines.push(String::new());
    } else {
        lines.push("## Active".to_string());
        lines.push(String::new());
        lines.push("| ID | Status | Owner | Priority | Title |".to_string());
        lines.push("|----|--------|-------|----------|-------|".to_string());
        for task in &active {
            lines.push(format!(
                "| {} | {} | {} | {} | {} |",
                cell(task.get_str("id").as_deref()),
                cell(task.get_str("status").as_deref()),
                cell(task.get_str("owner").as_deref()),
                cell(task.get_str("priority").as_deref()),
                cell(task.get_str("title").as_deref())
            ));
        }
        lines.push(String::new());
    }
    if !done.is_empty() {
        lines.push("## Recently done".to_string());
        lines.push(String::new());
        let mut sorted: Vec<&Task> = done;
        sorted.sort_by(|a, b| {
            b.get_str("updated")
                .unwrap_or_default()
                .cmp(&a.get_str("updated").unwrap_or_default())
        });
        for task in sorted.into_iter().take(20) {
            lines.push(format!(
                "- {} - {} ({})",
                text(task.get_str("id").as_deref()),
                text(task.get_str("title").as_deref()),
                text(task.get_str("updated").as_deref())
            ));
        }
        lines.push(String::new());
    }
    write_text_atomic(&ws.board_path(), &lines.join("\n"))
}

fn truncate(value: &str, width: usize) -> String {
    value.chars().take(width).collect()
}
